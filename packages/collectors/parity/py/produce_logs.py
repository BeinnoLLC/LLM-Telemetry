#!/usr/bin/env python3
"""Python-side producer for the logs parity case (T-16, LLMTELEMET-287).

Usage: produce_logs.py INPUTS_DIR OUT_DIR ARTIFACT

Runs the REAL `llm_telemetry.collect_logs.build()` against the profiles
generated by make_logs_fixture.py, with HOME and the config pointed into
INPUTS_DIR, then the same atomic write as produce.py (no payload schema exists).
"""
import json
import os
import sys


def main(argv):
    if len(argv) != 3:
        sys.stderr.write("usage: produce_logs.py INPUTS_DIR OUT_DIR ARTIFACT\n")
        return 2
    inputs, out_dir, artifact = (os.path.abspath(argv[0]), argv[1], argv[2])
    os.environ["HOME"] = os.path.join(inputs, "home")
    os.environ["LLM_TELEMETRY_CONFIG"] = os.path.join(inputs, "config.json")
    os.environ["LLM_TELEMETRY_AGENT_HOME"] = os.path.join(inputs, "agent")
    now = os.environ.get("LLM_TELEMETRY_PARITY_NOW")
    if now:
        import time
        fixed = float(now)
        time.time = lambda: fixed
    from llm_telemetry import collect_logs
    data = collect_logs.build()
    os.makedirs(out_dir, exist_ok=True)
    target = os.path.join(out_dir, artifact)
    tmp = target + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        json.dump(data, fh, separators=(",", ":"), default=str)
    os.replace(tmp, target)
    sys.stdout.write(target + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
