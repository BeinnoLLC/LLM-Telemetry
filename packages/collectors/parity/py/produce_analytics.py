#!/usr/bin/env python3
"""Python-side producer for the analytics parity case (T-15, LLMTELEMET-286).

Usage: produce_analytics.py INPUTS_DIR OUT_DIR ARTIFACT

Runs the REAL `llm_telemetry.collect_analytics.build()` against the fixture
inputs generated by make_analytics_fixture.py (config, pinned catalogue, state
DBs, orchestration store), with HOME pointed into INPUTS_DIR so nothing under
the real home is read. Then the same schema_check + atomic write as produce.py.
"""
import json
import os
import sys


def main(argv):
    if len(argv) != 3:
        sys.stderr.write("usage: produce_analytics.py INPUTS_DIR OUT_DIR ARTIFACT\n")
        return 2
    inputs, out_dir, artifact = (os.path.abspath(argv[0]), argv[1], argv[2])
    os.environ["HOME"] = os.path.join(inputs, "home")
    os.environ["LLM_TELEMETRY_CONFIG"] = os.path.join(inputs, "config.json")
    os.environ["LLM_TELEMETRY_CATALOG"] = os.path.join(inputs, "catalog.json")
    os.environ["LLM_TELEMETRY_AGENT_HOME"] = os.path.join(inputs, "agent")
    now = os.environ.get("LLM_TELEMETRY_PARITY_NOW")
    if now:
        # One shared clock with the Node producer: time.time() and the module's
        # datetime.now() read the same instant (SQLite's 'now' is not patchable).
        import datetime
        import time
        fixed = float(now)
        time.time = lambda: fixed

        class _Dt(datetime.datetime):
            @classmethod
            def now(cls, tz=None):
                return datetime.datetime.fromtimestamp(fixed, tz)
        datetime.datetime = _Dt
    from llm_telemetry import collect_analytics
    from llm_telemetry.schema_check import check
    data = collect_analytics.build()
    check("analytics", data)
    os.makedirs(out_dir, exist_ok=True)
    target = os.path.join(out_dir, artifact)
    tmp = target + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        json.dump(data, fh, separators=(",", ":"), default=str)
    os.replace(tmp, target)
    sys.stdout.write(target + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
